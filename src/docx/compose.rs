//! Canonical composition of Latin letters with combining marks.

/// Word shapes a letter followed by a combining mark as the precomposed glyph
/// (air_pollution's "t" + U+030C draws as "ť", 0.53 em wide in Times New
/// Roman); drawing the two glyphs apart misplaces the accent and the advance.
// ponytail: Latin only (U+00C0–024F, U+1E00–1EFF); Greek and Cyrillic marks
// stay decomposed until a document needs them.
pub(crate) fn compose_latin(text: String) -> String {
    if !text.chars().any(is_mark) {
        return text;
    }
    let mut out = String::with_capacity(text.len());
    let mut last: Option<char> = None;
    for ch in text.chars() {
        if is_mark(ch)
            && let Some(base) = last
            && let Ok(i) = PAIRS.binary_search_by(|&(b, m, _)| (b, m).cmp(&(base, ch)))
        {
            last = Some(PAIRS[i].2);
            continue;
        }
        out.extend(last.replace(ch));
    }
    out.extend(last);
    out
}

pub(crate) fn is_mark(ch: char) -> bool {
    ('\u{0300}'..='\u{036F}').contains(&ch)
}

