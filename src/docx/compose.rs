#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn composes_marks_onto_their_letters() {
        assert_eq!(compose_latin("Z\u{30C}iadost\u{30C}".into()), "Žiadosť");
        // Stacked marks compose one at a time: e + dot below + circumflex.
        assert_eq!(compose_latin("e\u{323}\u{302}".into()), "ệ");
        // No precomposed form: the mark stays.
        assert_eq!(compose_latin("q\u{301}".into()), "q\u{301}");
        assert!(PAIRS.windows(2).all(|w| (w[0].0, w[0].1) < (w[1].0, w[1].1)));
    }
}
